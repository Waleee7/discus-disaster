// Keys the green-screen sheets in art-src/ into transparent atlases in art/ and writes src/artAtlas.js.
// Items are found automatically; their order (rows top to bottom, left to right) is what src/cards.js names.
// Each sheet is also written at half size (art/<sheet>-half.webp, same layout so the same UVs) for phones.
//   node scripts/build-art.mjs
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const require = createRequire(process.env.HOME + '/.claude/scripts/');
const { chromium } = require('playwright');
const SHEETS = ['kit-a', 'kit-b', 'hotdog-a', 'hotdog-b'];
mkdirSync('art', { recursive: true });
const b = await chromium.launch();
const page = await b.newPage();
const atlas = {};
for (const sheet of SHEETS) {
  const u = 'data:image/jpeg;base64,' + readFileSync(`art-src/${sheet}.jpg`).toString('base64');
  const r = await page.evaluate(async (u) => {
    const i = new Image(); i.src = u; await i.decode();
    const w = i.width, h = i.height, c = document.createElement('canvas'); c.width = w; c.height = h;
    const x = c.getContext('2d', { willReadFrequently: true }); x.drawImage(i, 0, 0);
    const im = x.getImageData(0, 0, w, h), d = im.data, on = new Uint8Array(w * h);
    for (let n = 0, p = 0; n < w * h; n++, p += 4) {
      const R = d[p], G = d[p + 1], B = d[p + 2], key = G - Math.max(R, B);
      const a = key > 80 ? 0 : key < 28 ? 255 : Math.round((255 * (80 - key)) / 52);
      d[p + 3] = a;
      if (key > 0) d[p + 1] = Math.max(R, B); // pull the green spill off the edges
      if (a > 128) on[n] = 1;
    }
    x.putImageData(im, 0, 0);
    // connected islands on a coarse grid: an item is every solid cell reachable with a small gap allowed
    const S = 6, gw = Math.ceil(w / S), gh = Math.ceil(h / S), grid = new Int32Array(gw * gh);
    for (let y = 0; y < h; y++) for (let X = 0; X < w; X++) if (on[y * w + X]) grid[((y / S) | 0) * gw + ((X / S) | 0)]++;
    const seen = new Uint8Array(gw * gh), items = [];
    for (let s = 0; s < gw * gh; s++) {
      if (seen[s] || grid[s] < 3) continue;
      let x0 = 1e9, x1 = -1, y0 = 1e9, y1 = -1, n = 0; const st = [s]; seen[s] = 1;
      while (st.length) {
        const q = st.pop(), qx = q % gw, qy = (q / gw) | 0; n += grid[q];
        x0 = Math.min(x0, qx); x1 = Math.max(x1, qx); y0 = Math.min(y0, qy); y1 = Math.max(y1, qy);
        for (let dy = -3; dy <= 3; dy++) for (let dx = -3; dx <= 3; dx++) {
          const nx = qx + dx, ny = qy + dy; if (nx < 0 || ny < 0 || nx >= gw || ny >= gh) continue;
          const k = ny * gw + nx; if (!seen[k] && grid[k] >= 3) { seen[k] = 1; st.push(k); }
        }
      }
      if (n > 150) items.push({ x: Math.max(0, x0 * S - 2), y: Math.max(0, y0 * S - 2), w: Math.min(w, (x1 + 1) * S + 2) - Math.max(0, x0 * S - 2), h: Math.min(h, (y1 + 1) * S + 2) - Math.max(0, y0 * S - 2) });
    }
    items.sort((a, b) => a.y + a.h / 2 - (b.y + b.h / 2));
    const hc = document.createElement('canvas');
    hc.width = Math.round(w / 2);
    hc.height = Math.round(h / 2);
    const hx = hc.getContext('2d');
    hx.imageSmoothingQuality = 'high';
    hx.drawImage(c, 0, 0, hc.width, hc.height);
    return { w, h, items, data: c.toDataURL('image/webp', 0.88), half: hc.toDataURL('image/webp', 0.86) };
  }, u);
  writeFileSync(`art/${sheet}.webp`, Buffer.from(r.data.split(',')[1], 'base64'));
  writeFileSync(`art/${sheet}-half.webp`, Buffer.from(r.half.split(',')[1], 'base64'));
  atlas[sheet] = { w: r.w, h: r.h, items: r.items };
  console.log(sheet, r.w + 'x' + r.h, r.items.length, 'items', Math.round(r.data.length * 0.75 / 1024) + 'KB');
}
await b.close();
writeFileSync('src/artAtlas.js', '// Generated by scripts/build-art.mjs\nexport const ART_ATLAS = ' + JSON.stringify(atlas) + ';\n');
